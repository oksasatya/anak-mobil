-- The Indonesian-market vehicle catalog: brand → model → generation → variant.
--
-- This is NOT the fake data the repository rules forbid. That rule is about
-- invented community counts, fabricated testimonials, and screenshots of
-- activity that never happened — the platform launches empty and says so.
-- A catalog of cars that genuinely exist is reference data.
--
-- 49 brands, 369 models, 468 generations, 898 variants: what is sold here now,
-- including the marques that arrived in the last three years, plus what is
-- still on the road and still being modified — Kijang, Starlet, Great Corolla,
-- Genio, Katana, Taruna, Lancer CB, W124. An enthusiast catalog that starts at
-- 2020 is missing most of what its users actually own.
--
-- STILL NOT EVERY CAR, and it says so rather than implying otherwise. The PRD
-- scopes the real catalog as a content job; `POST /catalog/suggestions` is the
-- escape hatch for a car that is missing, and it already exists.
--
-- WHAT IS DELIBERATELY BLANK, and why. Engine codes, displacement, power,
-- torque, and OEM offsets vary by market year and trim, and a plausible wrong
-- number in a fitment table is worse than a blank one — the same rule the
-- parts API enforces on user input applies to us. `missing_specs` exists to
-- report a gap honestly. Transmission, drivetrain, and fuel are set ONLY where
-- the trim name states them outright ("1.5 G CVT", "Dakar Ultimate 4x4",
-- "RS e:HEV"); reading a name is not the same as guessing a spec, so a trim
-- that names neither gets NULL rather than a default. PCD and centre bore are
-- published and stable per platform, so they are applied per generation at the
-- end of this file for the platforms where they are known.
--
-- `brands.logo_domain` is the brand's own primary domain, and it is what the
-- clients hand to a logo CDN. Storing a DOMAIN rather than an image URL is the
-- point: the CDN, its sizing, and its API key are a client concern that can
-- change without a migration, and the domain is a stable fact about the brand.
--
-- Idempotent: re-running changes nothing. The natural key is the slug scoped
-- to its parent — only `brands.slug` is globally unique, and models,
-- generations, and variants are unique per parent. The prefixes below keep
-- them readable and unambiguous anyway, which is what lets the joins here
-- look a row up by slug alone.
--
-- A development database seeded with the older starter file keeps that file's
-- generation rows, whose slugs differ from these — `make db-drop && make
-- db-seed` is the way to get a clean catalog.

